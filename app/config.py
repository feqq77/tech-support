"""Application configuration loading.

Precedence: environment variables > project config.env > defaults.

config.env is generated by install.sh (with a random technician token) and
never contains production secrets committed to the repository.
"""

from __future__ import annotations

import os
import pathlib
from dataclasses import dataclass

PROJECT_ROOT = pathlib.Path(__file__).resolve().parent.parent
CONFIG_FILE = PROJECT_ROOT / "config.env"


@dataclass
class AppConfig:
    signaling_url: str = "ws://127.0.0.1:8787/ws"
    tech_token: str = ""
    support_code: str = "1234"
    ice_servers_json: str = ""


def _parse_env_file(path: pathlib.Path) -> dict:
    values: dict = {}
    if not path.is_file():
        return values
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        values[key.strip()] = val.strip().strip('"').strip("'")
    return values


def load_config() -> AppConfig:
    file_vals = _parse_env_file(CONFIG_FILE)
    return AppConfig(
        signaling_url=os.environ.get(
            "SIGNALING_URL", file_vals.get("SIGNALING_URL", "ws://127.0.0.1:8787/ws")
        ),
        tech_token=os.environ.get(
            "SUPPORT_TECH_TOKEN", file_vals.get("SUPPORT_TECH_TOKEN", "")
        ),
        support_code=os.environ.get(
            "SUPPORT_CODE", file_vals.get("SUPPORT_CODE", "1234")
        ),
        ice_servers_json=os.environ.get(
            "ICE_SERVERS_JSON", file_vals.get("ICE_SERVERS_JSON", "")
        ),
    )
